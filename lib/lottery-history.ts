function bangkokDateParts(): { day: number; month: number; year: number } {
  const parts = new Intl.DateTimeFormat('en-US-u-ca-gregory', {
    timeZone: 'Asia/Bangkok',
    day: 'numeric',
    month: 'numeric',
    year: 'numeric',
  }).formatToParts(new Date());
  return {
    day: Number(parts.find((part) => part.type === 'day')?.value ?? 1),
    month: Number(parts.find((part) => part.type === 'month')?.value ?? 1),
    year: Number(parts.find((part) => part.type === 'year')?.value ?? 2026),
  };
}

export function defaultLotteryDrawDate(): string {
  const today = bangkokDateParts();
  const day = today.day <= 1 ? 1 : today.day <= 16 ? 16 : 1;
  const target = new Date(Date.UTC(today.year, today.month - 1, today.day > 16 ? 1 : day));
  if (today.day > 16) target.setUTCMonth(target.getUTCMonth() + 1);
  return [
    target.getUTCFullYear(),
    String(target.getUTCMonth() + 1).padStart(2, '0'),
    String(target.getUTCDate()).padStart(2, '0'),
  ].join('-');
}

export function lotteryRoundDateLabel(dateValue: string): string {
  const match = dateValue.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return dateValue;
  const year = Number(match[1]) + 543;
  const month = Number(match[2]);
  const day = Number(match[3]);
  const monthName = lotteryHistoryMonths[month - 1];
  return monthName ? `${day} ${monthName} ${year}` : dateValue;
}

export function lotteryRoundKeyForDate(dateValue: string): string | null {
  const match = dateValue.match(/^\d{4}-(\d{2})-(\d{2})$/);
  if (!match) return null;
  return `${Number(match[2])}-${Number(match[1])}`;
}

export function historicalLotteryRoundKey(date: string): string | null {
  const match = date.match(/^(\d{1,2})\s+(\S+)\s+\d{4}$/);
  if (!match) return null;

  let day = Number(match[1]);
  const month = lotteryHistoryMonths.indexOf(
    match[2] as (typeof lotteryHistoryMonths)[number],
  ) + 1;
  if (!month) return null;

  // บางงวดเลื่อนจากวันกำหนดเพราะวันหยุดหรือเหตุพิเศษ
  if (month === 1 && day === 17) day = 16;
  else if ((month === 1 || month === 5) && day === 2) day = 1;
  else if (month === 7 && day === 31) day = 16;

  return `${day}-${month}`;
}
